    /// <summary>定額法償却率（別表第八: 1/耐用年数 を小数第3位で切り上げ）</summary>
    public static decimal StraightLineRate(int usefulLifeYears)
    {
        if (usefulLifeYears < 1) throw new ArgumentOutOfRangeException(nameof(usefulLifeYears));
        return Math.Ceiling(1000m / usefulLifeYears) / 1000m;
    }

    /// <summary>200%定率法の (償却率, 改定償却率, 保証率)。耐用年数2年は改定/保証なし。</summary>
    public static Db200Rate DecliningBalance200(int usefulLifeYears)
    {
        if (Db200.TryGetValue(usefulLifeYears, out var r)) return r;
        throw new ArgumentOutOfRangeException(
            nameof(usefulLifeYears),
            $"定率法(200%)の償却率表は耐用年数 2〜{MaxSupportedYear} 年まで収録。指定値: {usefulLifeYears}");
    }

